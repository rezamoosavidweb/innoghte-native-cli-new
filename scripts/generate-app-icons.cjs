/*
 * Regenerate native launcher assets from the existing Innoghte vector logo.
 * Requires Node.js and sharp (available via node_modules or NODE_PATH).
 * Run from any directory: node scripts/generate-app-icons.cjs
 * No raster source or added runtime dependency is needed by the app.
 */
const fs = require('node:fs/promises');
const path = require('node:path');
const sharp = require('sharp');

const root = path.resolve(__dirname, '..');
const res = path.join(root, 'android/app/src/main/res');
const iconSet = path.join(
  root,
  'ios/Innoghte/Images.xcassets/AppIcon.appiconset',
);
const markSize = 50.1732;
const markLeft = 68.5747;

async function write(file, content) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content);
}

async function main() {
  const logo = await fs.readFile(
    path.join(root, 'src/assets/logo.svg'),
    'utf8',
  );
  const emblem = logo.match(/<g clip-path="[^"]+">([\s\S]*?)<\/g>/)?.[1];
  const paths = [...(emblem ?? '').matchAll(/<path d="([^"]+)"/g)].map(
    match => match[1],
  );
  if (paths.length !== 2) {
    throw new Error(
      'Expected the two existing circle/person paths in logo.svg. Review the source before regenerating.',
    );
  }

  const mark = paths.map(d => `<path d="${d}" fill="#000000"/>`).join('\n');
  const svg = (size, markRatio, round = false) => {
    const inset = (size * (1 - markRatio)) / 2;
    const background = round
      ? `<circle cx="${size / 2}" cy="${size / 2}" r="${
          size / 2
        }" fill="#FFFFFF"/>`
      : `<rect width="${size}" height="${size}" fill="#FFFFFF"/>`;
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
${background}
<svg x="${inset}" y="${inset}" width="${size * markRatio}" height="${
      size * markRatio
    }" viewBox="${markLeft} 0 ${markSize} ${markSize}">
${mark}
</svg>
</svg>
`;
  };

  const source = svg(1024, 0.78);
  await write(path.join(root, 'src/assets/app-icon.svg'), source);

  // Legacy launchers (API 24–25): both manifest icon entries are circular.
  for (const [density, size] of Object.entries({
    mdpi: 48,
    hdpi: 72,
    xhdpi: 96,
    xxhdpi: 144,
    xxxhdpi: 192,
  })) {
    const png = await sharp(Buffer.from(svg(size * 4, 0.82, true)))
      .resize(size, size)
      .png()
      .toBuffer();
    for (const name of ['ic_launcher', 'ic_launcher_round']) {
      await write(path.join(res, `mipmap-${density}/${name}.png`), png);
    }
  }

  // A 62dp emblem stays inside the 66dp circular safe zone of the 108dp layer.
  const scale = 62 / markSize;
  const offset = (108 - 62) / 2;
  const vector = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-app-icons.cjs from src/assets/logo.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="${offset}" android:translateY="${offset}">
        <group android:scaleX="${scale}" android:scaleY="${scale}">
            <group android:translateX="${-markLeft}">
${paths
  .map(
    d =>
      `                <path android:fillColor="#FF000000" android:pathData="${d}"/>`,
  )
  .join('\n')}
            </group>
        </group>
    </group>
</vector>
`;
  await write(path.join(res, 'drawable/ic_launcher_foreground.xml'), vector);
  await write(
    path.join(res, 'values/ic_launcher_background.xml'),
    `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#FFFFFF</color>
</resources>
`,
  );

  for (const api of [26, 33]) {
    const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
${
  api === 33
    ? '    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>\n'
    : ''
}</adaptive-icon>
`;
    for (const name of ['ic_launcher', 'ic_launcher_round']) {
      await write(
        path.join(res, `mipmap-anydpi-v${api}/${name}.xml`),
        adaptive,
      );
    }
  }

  // iPhone, iPad, notifications, Settings, Spotlight and the App Store.
  const slots = [
    ['iphone', 20, [2, 3]],
    ['iphone', 29, [2, 3]],
    ['iphone', 40, [2, 3]],
    ['iphone', 60, [2, 3]],
    ['ipad', 20, [1, 2]],
    ['ipad', 29, [1, 2]],
    ['ipad', 40, [1, 2]],
    ['ipad', 76, [1, 2]],
    ['ipad', 83.5, [2]],
    ['ios-marketing', 1024, [1]],
  ];
  const images = [];
  const rendered = new Set();
  for (const [idiom, points, scales] of slots) {
    for (const factor of scales) {
      const pixels = points * factor;
      const filename = `AppIcon-${pixels}.png`;
      if (!rendered.has(pixels)) {
        const png = await sharp(Buffer.from(source))
          .resize(pixels, pixels)
          .flatten({ background: '#FFFFFF' })
          .removeAlpha()
          .png()
          .toBuffer();
        await write(path.join(iconSet, filename), png);
        rendered.add(pixels);
      }
      images.push({
        filename,
        idiom,
        scale: `${factor}x`,
        size: `${points}x${points}`,
      });
    }
  }
  await write(
    path.join(iconSet, 'Contents.json'),
    `${JSON.stringify(
      { images, info: { author: 'xcode', version: 1 } },
      null,
      2,
    )}\n`,
  );
  console.log(
    `Generated Android legacy/adaptive/themed icons and ${images.length} iOS slots (${rendered.size} opaque PNGs).`,
  );
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
